// src/apps/desktop_app/main.zig
//
// Chunk 8 (with --pabrik-url extension): the real lifecycle. Wires CLI
// parsing → mode branch → (spawn-mode: resolve → port → extract → spawn
// → healthcheck → webview) OR (connect-mode: just webview) → cleanup.
//
// Two startup modes:
//
//   Spawn mode (default):
//     1. Parse CLI flags (--port, --pabrik-path, --window-size, --title, etc.)
//     2. Locate the pabrik binary (--pabrik-path → next-to-self → $PATH)
//     3. Allocate a free TCP port (or honour --port NNNN)
//     4. Extract the comptime-embedded webapp assets to a per-pid temp dir
//     5. Spawn `pabrik --port <port>` as a child process
//     6. Poll GET /health until 200 (max 10s)
//     7. Open a native webview window pointed at http://127.0.0.1:<port>/
//     8. Run the platform event loop (blocks until the window closes)
//     9. On window close: SIGTERM pabrik, wait up to 2s, SIGKILL if still
//        alive, then exit 0.
//
//   Connect mode (--pabrik-url URL):
//     1. Parse CLI flags
//     2. Open the webview directly at the given URL
//     3. Run the platform event loop
//     4. On window close, exit 0. (No child pabrik to clean up — the
//        external pabrik that the user started keeps running.)
//
// The dev workflow that motivated connect mode: you already have pabrik
// running on :8081 (your TUI/dev pabrik), and you want a window wrapper.
// `--pabrik-url http://127.0.0.1:8081` does that without spawning a
// second pabrik on :8080.

