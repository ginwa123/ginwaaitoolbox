pub fn main(init: std.process.Init) !void {
    const allocator = init.gpa;
    const io = init.io;
    // init.environ_map is used below (read PATH for attach.zig's auto-spawn).

    // 1. Parse CLI args. `init.minimal.args` is a `process.Args` iterator
    // in Zig 0.16 (not a slice), so we materialize it into an ArrayList.
    // Use `initAllocator` (NOT `init`) — `Args.Iterator.init` raises a
    // `@compileError` on Windows in Zig 0.16: "In Windows, use
    // initAllocator instead." `initAllocator` works on every platform.
    var args_buf: std.ArrayList([]const u8) = .empty;
    defer args_buf.deinit(allocator);
    var args_iter = try std.process.Args.Iterator.initAllocator(init.minimal.args, allocator);
    defer args_iter.deinit();
    while (args_iter.next()) |arg| {
        try args_buf.append(allocator, arg);
    }

    var cfg = cli.parse(allocator, args_buf.items) catch |err| switch (err) {
        error.ShowHelp => return,
        else => {
            std.log.err("Failed to parse CLI args: {s}", .{@errorName(err)});
            return err;
        },
    };
    defer cfg.deinit(allocator);

    // Headless smoke test (Chunk 2.1): bypass both spawn and webview paths
    // entirely. WebKitGTK cannot initialise without a display server, so the
    // best we can do on a CI runner is verify the binary loads, parses CLI,
    // resolves its webapp dir, and exits 0 cleanly. CI invokes this via
    // `./zig-out/bin/pabrik-desktop --smoke-test` after build.
    //
    // The resolution below mirrors real startup (see ATTACH MODE): installed
    // html/ first via findInstalledWebapp, persistent content-addressed
    // materialisation as fallback. On Windows CI this proves the exe actually
    // selects the shipped html/ sitting beside it (the dir the webview backend
    // is served from) instead of the embedded stub.
    if (cfg.smoke_test) {
        const self_exe_smoke = path_resolve.selfExePath(allocator) catch ".";
        defer if (!std.mem.eql(u8, self_exe_smoke, ".")) allocator.free(self_exe_smoke);
        if (path_resolve.findInstalledWebapp(allocator, self_exe_smoke)) |installed| {
            defer allocator.free(installed);
            std.log.info("smoke: using installed webapp at {s} (no extraction)", .{installed});
            return;
        }
        const webapp_dir = extraction.ensurePersistentStable(allocator, webapp_assets.assets) catch |err| {
            std.log.err("smoke: webapp materialisation failed: {s}", .{@errorName(err)});
            return err;
        };
        defer allocator.free(webapp_dir);
        std.log.info("smoke: {d} assets materialised at {s}", .{ webapp_assets.assets.len, webapp_dir });
        return;
    }

    // 1b. Connect mode (--pabrik-url): skip the entire spawn path. The
    // user has their own pabrik running and we just point the webview at
    // it. --port and --pabrik-path are ignored. Asset extraction is also
    // skipped (the external pabrik is responsible for serving the webapp).
    if (cfg.pabrik_url) |url| {
        std.log.info("Connect mode: connecting to {s} (no spawn)", .{url});
        if (cfg.browser) {
            try browser.openBrowser(io, url);
            return;
        }
        try runWebview(allocator, cfg, url);
        return;
    }

    // SPAWN MODE was removed in the decoupled-pabrik-service refactor.
    // The desktop now ONLY attaches to an already-running pabrik (or
    // asks the user to start one). The new flow lives in the
    // "ATTACH MODE" block below.

    // ATTACH MODE (default + new behavior).
    //
    // Resolve the desktop's own exe path early: attach.zig needs it for
    // the "next to self" pabrik lookup AND the Windows installed-webapp
    // lookup below. Best-effort: on platforms without /proc/self/exe,
    // fall back to "." and let both lookups skip their exe-relative
    // checks.
    const self_exe_owned = path_resolve.selfExePath(allocator) catch ".";
    defer if (!std.mem.eql(u8, self_exe_owned, ".")) allocator.free(self_exe_owned);

    // 1. Choose the webapp dir to serve via `--static-dir` on auto-spawn.
    //    Windows-only shipped layout: prefer the persistent installed copy
    //    (%LOCALAPPDATA%\pabrik\html, then html/ next to the exe -- see
    //    path_resolve.findInstalledWebapp) so close/reopen and reboot keep
    //    working with no per-run temp extraction.
    //
    //    Otherwise materialise the embedded assets into a PERSISTENT,
    //    content-addressed per-user dir and hand out its stable
    //    `<base>/current` symlink (extraction.ensurePersistentStable), so
    //    `ps` always shows one path no matter how many versioned `<hash>`
    //    dirs sit behind the link.
    //
    //    That dir is NEVER deleted by the desktop, and that is load
    //    bearing. The pabrik daemon spawned below is deliberately detached
    //    (closing the window does not signal it), so it keeps serving
    //    `--static-dir <this dir>` long after the desktop exits. The old
    //    per-pid temp dir was deleted at exit by extraction.cleanup, so
    //    the next launch attached to a daemon whose static dir was gone:
    //    /health still answered 200, GET / answered 404 Not Found, and
    //    the webview opened on a blank page.
    //
    //    Ownership: both branches hand back a slice the caller frees;
    //    neither dir is ever removed.
    var webapp_dir: []u8 = undefined;
    if (path_resolve.findInstalledWebapp(allocator, self_exe_owned)) |installed| {
        webapp_dir = installed;
        std.log.info("Using installed webapp at {s}", .{webapp_dir});
    } else {
        webapp_dir = extraction.ensurePersistentStable(allocator, webapp_assets.assets) catch |err| {
            std.log.err("Failed to materialise webapp assets: {s}", .{@errorName(err)});
            return err;
        };
        std.log.info("Using persistent webapp at {s}", .{webapp_dir});
    }
    defer allocator.free(webapp_dir);



    // 2. Resolve the attach target via attach.zig: probe state file
    //    → health → connect. If pabrik isn't running and --no-auto-start
    //    was passed, surface an actionable error.
    const state_path = pabrikcore.state_file.defaultStatePath(allocator) catch |err| {
        std.log.err("Failed to resolve state.json path: {s}", .{@errorName(err)});
        return err;
    };
    defer allocator.free(state_path);

    // (self_exe_owned was resolved above -- it feeds both the
    // installed-webapp lookup and the attach target below.)

    // PATH env (for the auto-spawn fallback when --pabrik-path is unset
    // and pabrik isn't next to the desktop binary).
    //
    // NOTE: `init.environ_map.get(key)` returns a `[]const u8` slice
    // that points into the Environ map's INTERNAL storage (a borrow,
    // not an owned allocation). We MUST NOT call `allocator.free` on
    // it — that's the double-free the smoke test caught. The `[]const u8`
    // has the same lifetime as `init.environ_map` (the entire process),
    // which is fine for our use.
    const path_env = init.environ_map.get("PATH") orelse "";

    const attach_target = attach.resolveAttachTarget(allocator, io, .{
        .state_path = state_path,
        .default_port = if (cfg.attach_port == 0) 8081 else cfg.attach_port,
        .no_auto_start = cfg.no_auto_start,
        .pabrik_path = cfg.pabrik_path,
        .self_exe_path = self_exe_owned,
        .path_env = path_env,
        .static_dir = webapp_dir,
    }) catch |err| switch (err) {
        error.AutoStartDisabled => {
            std.log.err("pabrik is not running.", .{});
            std.log.err("Run `pabrik service start` in a terminal first, then re-open the desktop.", .{});
            return err;
        },
        error.PabrikNotFound => {
            // Already logged from attach.zig with hints; just exit cleanly.
            return err;
        },
        error.AutoSpawnFailed => {
            // Already logged from attach.zig with hints; just exit cleanly.
            return err;
        },
        else => return err,
    };
    defer allocator.free(attach_target.host);

    // 2. Build the URL.
    const url = try std.fmt.allocPrint(allocator, "http://{s}:{d}/", .{ attach_target.host, attach_target.port });
    defer allocator.free(url);

    // 3. Open the UI. Browser-tab mode exits right after handing the
    //    URL to the OS; webview mode blocks until the window closes.
    //    No defer terminate in either case — the desktop's lifetime
    //    is decoupled from pabrik's. Closing the window/tab does NOT
    //    signal pabrik; only `pabrik service stop` does.
    std.log.info("Attaching to pabrik at {s} (we_spawned={any})", .{ url, attach_target.we_spawned });
    if (cfg.browser) {
        try browser.openBrowser(io, url);
        return;
    }
    // Windows: prefer a bundled fixed-version WebView2 runtime when the
    // release zip shipped one next to the exe (no install needed).
    if (comptime builtin.os.tag == .windows) {
        pointWebView2AtBundledRuntime(allocator, self_exe_owned);
    }
    try runWebview(allocator, cfg, url);
}

/// Open the webview window and run the platform event loop (blocks
/// until the window closes). Thin pass-through to the vendored
/// webview/webview library — everything the library does by default is
/// what ships (including its built-in WebKit DMA-BUF/NVIDIA
/// workaround and clipboard-access setting).
///
/// The backend serves the webapp over http://127.0.0.1:PORT, so no
/// custom scheme handler or embedded asset table is needed.
// Windows-only: point the WebView2 loader at a bundled fixed-version
// runtime when `<exe-dir>\webview2-runtime\msedgewebview2.exe` exists
// (release-zip layout; see the CI bundle step). The vendored webview
// library passes nullptr as browser_dir, so the loader honors the
// WEBVIEW2_BROWSER_EXECUTABLE_FOLDER env var with no C++ changes.
// No-op when no bundled runtime is present -- the loader then falls back
// to the evergreen registry lookup as before.
//
// Fixed-version layout (Microsoft docs): `expand <.cab> -F:* <dir>`
// yields a dir whose ROOT holds msedgewebview2.exe -- that dir is what
// the env var must point at.
extern "kernel32" fn SetEnvironmentVariableW(lpName: [*:0]const u16, lpValue: [*:0]const u16) callconv(.winapi) c_int;

fn pointWebView2AtBundledRuntime(allocator: std.mem.Allocator, self_exe_path: []const u8) void {
    if (comptime builtin.os.tag != .windows) return;
    const exe_dir = std.fs.path.dirname(self_exe_path) orelse return;
    const runtime_dir = std.fs.path.join(allocator, &.{ exe_dir, "webview2-runtime" }) catch return;
    defer allocator.free(runtime_dir);
    const probe = std.fs.path.join(allocator, &.{ runtime_dir, "msedgewebview2.exe" }) catch return;
    defer allocator.free(probe);
    var probe_buf: [std.fs.max_path_bytes:0]u8 = undefined;
    if (probe.len >= probe_buf.len) return;
    @memcpy(probe_buf[0..probe.len], probe);
    probe_buf[probe.len] = 0;
    if (std.c.access(&probe_buf, std.c.F_OK) != 0) return; // no bundled runtime -- evergreen lookup as usual
    var name_wide: [64]u16 = undefined;
    var value_wide: [std.fs.max_path_bytes]u16 = undefined;
    const name_len = std.unicode.wtf8ToWtf16Le(&name_wide, "WEBVIEW2_BROWSER_EXECUTABLE_FOLDER") catch return;
    if (name_len >= name_wide.len) return;
    name_wide[name_len] = 0;
    const value_len = std.unicode.wtf8ToWtf16Le(&value_wide, runtime_dir) catch return;
    if (value_len >= value_wide.len) return;
    value_wide[value_len] = 0;
    if (SetEnvironmentVariableW(@ptrCast(&name_wide), @ptrCast(&value_wide)) == 0) return;
    std.log.info("Using bundled WebView2 runtime at {s}", .{runtime_dir});
}
fn runWebview(
    allocator: std.mem.Allocator,
    cfg: cli.Config,
    url: []const u8,
) !void {
    // Null-terminate the strings the C ABI expects.
    const title_z = try allocator.dupeZ(u8, cfg.title);
    defer allocator.free(title_z);
    const url_z = try allocator.dupeZ(u8, url);
    defer allocator.free(url_z);

    std.log.info("Opening webview at {s}", .{url});
    webview_lib.runWindow(
        title_z.ptr,
        url_z.ptr,
        @intCast(cfg.window_width),
        @intCast(cfg.window_height),
        cfg.enable_devtools,
        cfg.force_x11,
    ) catch |err| {
        std.log.err("Webview error: {s}", .{@errorName(err)});
        // Windows: webview_create fails when the WebView2 EVERGREEN RUNTIME
        // is not installed on the machine. The WebView2Loader.dll beside
        // the exe is only the SDK forwarder -- it is not the runtime.
        // Tell the user exactly what to install instead of leaving them
        // with a bare error + stack trace. The backend from the attach
        // step above keeps running, so the app stays usable in any
        // Chromium browser at the logged URL in the meantime.
        if (builtin.os.tag == .windows) {
            std.log.err("The WebView2 window could not be created.", .{});
            std.log.err("Install the WebView2 evergreen runtime and re-run:", .{});
            std.log.err("  https://go.microsoft.com/fwlink/p/?LinkId=2124703", .{});
            std.log.err("Workaround: open {s} in Edge/Chrome (backend is running).", .{url});
        }
        return err;
    };
    std.log.info("Window closed. Exiting.", .{});
}

